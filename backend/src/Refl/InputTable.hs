-- | @(sequence, translations)@ pairs found in the elisp source.
parseAgdaInputEl :: Text -> [(Text, [Text])]
parseAgdaInputEl src = concatMap entry (T.splitOn "(\"" src)
 where
  entry chunk = case T.breakOn "\"" chunk of
    (key, rest)
      | T.null rest || T.null key -> []
      | otherwise ->
          let after = T.drop 1 rest
          in case T.stripPrefix " ." (T.dropWhile isSpace after) of
               Nothing -> []
               Just body ->
                 let b = T.dropWhile isSpace body
                 in if "(" `T.isPrefixOf` b then [(key, strings (T.takeWhile (/= ')') (T.drop 1 b)))]
                    else if ",(agda-input-to-string-list" `T.isPrefixOf` b
                      then case T.breakOn "\"" b of
                             (_, r) | T.null r -> []
                                    | otherwise -> [(key, map T.singleton (T.unpack (T.takeWhile (/= '"') (T.drop 1 r))))]
                      else []
  strings t = [ s | s <- T.splitOn "\"" t, not (T.null (T.strip s)), not (T.all isSpace s), s /= " " ]

-- | The Haskell module: a sorted association list; the frontend builds a
-- prefix map from it at startup.
renderInputModule :: [(Text, [Text])] -> Text
renderInputModule entries = T.unlines $
  [ "-- | Unicode input translations (agda-mode's \\ input method)."
  , "-- Generated by refl-gen-input-table; do not edit."
  , "module Widgets.InputTable (agdaTable) where"
  , ""
  , "import Data.Text (Text)"
  , ""
  , "agdaTable :: [(Text, [Text])]"
  , "agdaTable ="
  ] ++ zipWith row ("  [ " : repeat "  , ") (sortOn fst (M.toList merged)) ++ ["  ]"]
 where
  merged = M.fromListWith (\new old -> old ++ filter (`notElem` old) new)
             (filter (not . null . snd) (map clean (entries ++ extraTranslations)))
  clean (k, vs) = (k, filter (not . T.null) (map (T.filter (/= '"')) vs))
  row lead (k, vs) = lead <> "(" <> showT k <> ", [" <> T.intercalate ", " (map showT vs) <> "])"
  showT t = "\"" <> T.concatMap esc t <> "\""
  esc '\\' = "\\\\"
  esc '"'  = "\\\""
  esc c    = T.singleton c
