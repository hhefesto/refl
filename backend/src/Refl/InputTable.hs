-- | Extract agda-mode's unicode input translations from @agda-input.el@ and
-- render them as a Haskell module for the frontend.
--
-- The table in agda-input.el is an elisp alist; three entry shapes cover
-- essentially all of it:
--
-- > ("to" . ("→"))
-- > ("r" . ("→" "⇒" "↝"))
-- > ("Gr" . ,(agda-input-to-string-list "αβγ…"))
module Refl.InputTable
  ( parseAgdaInputEl
  , renderInputModule
  , extraTranslations
  ) where

import           Data.Char (isSpace)
import           Data.List (sortOn)
import qualified Data.Map  as M
import           Data.Text (Text)
import qualified Data.Text as T

